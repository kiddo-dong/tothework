           AS source_version,
       (SELECT COUNT(*) FROM ${identity}.users)
           + (SELECT COUNT(*) FROM ${identity}.email_tokens)
           + (SELECT COUNT(*) FROM ${identity}.refresh_tokens)
           + (SELECT COUNT(*) FROM ${store}.stores)
           + (SELECT COUNT(*) FROM ${store}.store_business_hours)
           + (SELECT COUNT(*) FROM ${store}.store_onboarding_steps)
           + (SELECT COUNT(*) FROM ${store}.store_members)
           + (SELECT COUNT(*) FROM ${store}.join_requests)
           + (SELECT COUNT(*) FROM ${workforce}.employment_terms)
           + (SELECT COUNT(*) FROM ${workforce}.employment_available_days)
           + (SELECT COUNT(*) FROM ${workforce}.shifts)
           + (SELECT COUNT(*) FROM ${workforce}.shift_templates)
           + (SELECT COUNT(*) FROM ${workforce}.attendances)
           + (SELECT COUNT(*) FROM ${workforce}.leave_usages)
           + (SELECT COUNT(*) FROM ${workforce}.payrolls)
           + (SELECT COUNT(*) FROM ${operations}.checklist_items)
           + (SELECT COUNT(*) FROM ${operations}.checklist_completions)
           + (SELECT COUNT(*) FROM ${operations}.notices)
           + (SELECT COUNT(*) FROM ${operations}.notice_reads)
           + (SELECT COUNT(*) FROM ${operations}.handover_notes)
           + (SELECT COUNT(*) FROM ${operations}.manuals)
           + (SELECT COUNT(*) FROM ${operations}.manual_images)
           + (SELECT COUNT(*) FROM ${operations}.suppliers)
           + (SELECT COUNT(*) FROM ${operations}.supplier_items)
           + (SELECT COUNT(*) FROM ${operations}.supplier_item_quantities)
           + (SELECT COUNT(*) FROM ${operations}.menu_ingredients)
           + (SELECT COUNT(*) FROM ${operations}.store_menus)
           + (SELECT COUNT(*) FROM ${operations}.menu_recipe_items)
           + (SELECT COUNT(*) FROM ${laborqa}.labor_qa_sessions)
           + (SELECT COUNT(*) FROM ${laborqa}.labor_qa_messages)
           AS target_rows;
